#include "pgm.h"

pgm_image_t *pgm_create(uint32_t width, uint32_t height, uint32_t max) {

	pgm_image_t *img = malloc(sizeof(pgm_image_t));
	if (!img) {
		return NULL;
	}

	img->width = width;
	img->height = height;
	img->max = max;

	img->pixels = malloc(height *sizeof(uint8_t*));
	if (!img->pixels) {
		free(img);
		return NULL;
	}

	for (uint32_t y = 0; y < height; y++) {
		img->pixels[y] = calloc(width, sizeof(uint8_t));
		if (!img->pixels[y]) {
			for(uint32_t k=0; k < y;k++){
				free(img->pixels[k]);
			}
			free(img->pixels);
			free(img);
			return NULL;
		}
	}

	return img;
}


void pgm_destroy(pgm_image_t *img) {

	if(!img) {
		return;
	}

	for (uint32_t y=0; y < img->height; y++) {
		free(img->pixels[y]);
	}

	free(img->pixels);
	free(img);
}

pgm_image_t *pgm_load(const char *filename) {

	FILE *f = fopen(filename, "r");
	if (!f) {
		fprintf(stderr, "Erreur : impossible d'ouvrir '%s' \n", filename);
		return NULL;
	}

	char magic[3];
	if(fscanf(f, "%2s", magic) !=1 || magic[0] != 'P' || magic[1] != '2') {
		fprintf(stderr, "Erreur : pas un fichier PGM P2\n");
		fclose(f);
		return NULL;
	}

	int c;
	while ((c = fgetc(f)) !=EOF) {
		if (c == '#') {
			while((c= fgetc(f)) != EOF && c != '\n');
		}else if (c != ' ' && c != '\t' && c != '\n' && c != '\r') {
			ungetc(c, f);
			break;
		}
	}

	uint32_t width, height, max;

	if (fscanf(f, "%u %u %u", &width, &height, &max) != 3) {
		fprintf(stderr, "Erreur : en-tête invalide\n");
		fclose(f);
		return NULL;
	}

	pgm_image_t *img = pgm_create(width, height, max);
	if (!img) {
		fclose(f);
		return NULL;
	}

	for (uint32_t y=0; y < height; y++) {
		for (uint32_t x = 0; x < width; x++) {
			unsigned int val;
			if (fscanf(f, "%u", &val) !=1) {
				fprintf(stderr, "Erreur : pixels incomplets\n");
				pgm_destroy(img);
				fclose(f);
				return NULL;
			}
			if (val > 255) {
				fprintf(stderr, "Erreur : valeur de pixel > 255 non supportée\n");
				pgm_destroy(img);
				fclose(f);
				return NULL;
			}
			img->pixels[y][x] = (uint8_t)val;
		}
	}

	fclose(f);
	printf("Image chargée : %ux%u, max=%u\n", width, height, max);
	return img;
}


bool pgm_save(const pgm_image_t *img, const char *filename) {
	if(!img) {
		return false;
	}

	FILE *f = fopen(filename, "w");

	if (!f) {
		fprintf(stderr, "Erreur : impossible de créer '%s'\n", filename);
		return false; 
	}

	fprintf(f, "P2\n");
	fprintf(f, "# generated by projet_image\n");
	fprintf(f, "%u %u\n", img->width, img->height);
	fprintf(f, "%u\n", img->max);

	for (uint32_t y = 0; y < img->height; y++) {
		for(uint32_t x=0; x < img->width; x++) {
			fprintf(f, "%3u", img->pixels[y][x]);
			if(x < img->width -1){
				fprintf(f, " ");
			}
		}
		fprintf(f, "\n");
	}

	fclose(f);
	printf("Image sauvegardée : '%s'\n", filename);
	return true;
}


pgm_image_t *pgm_pad(pgm_image_t *img) {
    if (!img) return NULL;

    // On cherche la puissance de 2 supérieure ou égale
    // à la plus grande dimension (largeur ou hauteur)
    uint32_t size = 1;
    uint32_t max_dim = img->width > img->height ? img->width : img->height;
    while (size < max_dim) size *= 2;

    pgm_image_t *padded = pgm_create(size, size, img->max);
    if (!padded) return NULL;

    // On copie les pixels de l'image originale
    for (uint32_t y = 0; y < img->height; y++) {
        for (uint32_t x = 0; x < img->width; x++) {
            padded->pixels[y][x] = img->pixels[y][x];
        }
    }

    return padded;
}
